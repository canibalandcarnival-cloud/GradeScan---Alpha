package com.example.util

import com.example.model.ColorGradingProfile
import java.util.Locale
import java.util.UUID

object XmpGenerator {

    fun buildPresetFileName(profile: ColorGradingProfile): String {
        val sanitized = profile.presetName
            .trim()
            .replace(Regex("[^A-Za-z0-9]+"), "_")
            .trim('_')
            .take(40)
            .ifBlank { "Studio_Look" }
        return "GradeScan_${sanitized}.xmp"
    }

    fun buildXmpContent(
        profile: ColorGradingProfile,
        uuid: String = UUID.randomUUID().toString().replace("-", "").uppercase(Locale.US)
    ): String {
        val escapedName = escapeXml(profile.presetName)
        val escapedNotes = escapeXml("${profile.moodSummary} — ${profile.moodNotes}")
        val exposureFormatted = formatSignedFloat(profile.exposure)

        return buildString {
            appendLine("""<?xml version="1.0" encoding="UTF-8"?>""")
            appendLine("""<x:xmpmeta xmlns:x="adobe:ns:meta/" x:xmptk="Adobe XMP Core 7.0-c000 1.000000, 0000/00/00-00:00:00        ">""")
            appendLine(""" <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">""")
            appendLine("""  <rdf:Description rdf:about="" """)
            appendLine("""    xmlns:crs="http://ns.adobe.com/camera-raw-settings/1.0/" """)
            appendLine("""    crs:PresetType="Normal" """)
            appendLine("""    crs:Cluster="" """)
            appendLine("""    crs:UUID="$uuid" """)
            appendLine("""    crs:SupportsAmount2="True" """)
            appendLine("""    crs:SupportsAmount="True" """)
            appendLine("""    crs:SupportsColor="True" """)
            appendLine("""    crs:SupportsMonochrome="True" """)
            appendLine("""    crs:SupportsHighDynamicRange="True" """)
            appendLine("""    crs:SupportsNormalDynamicRange="True" """)
            appendLine("""    crs:SupportsSceneReferred="True" """)
            appendLine("""    crs:SupportsOutputReferred="True" """)
            appendLine("""    crs:RequiresRGBTables="False" """)
            appendLine("""    crs:CameraModelRestriction="" """)
            appendLine("""    crs:Copyright="Generated by GradeScan" """)
            appendLine("""    crs:ContactInfo="" """)
            appendLine("""    crs:Version="15.0" """)
            appendLine("""    crs:ProcessVersion="11.0" """)
            appendLine("""    crs:WhiteBalance="Custom" """)
            appendLine("""    crs:Temperature="${profile.temperature}" """)
            appendLine("""    crs:Tint="${formatSignedInt(profile.tint)}" """)
            appendLine("""    crs:Exposure2012="$exposureFormatted" """)
            appendLine("""    crs:Contrast2012="${formatSignedInt(profile.contrast)}" """)
            appendLine("""    crs:Highlights2012="${formatSignedInt(profile.highlights)}" """)
            appendLine("""    crs:Shadows2012="${formatSignedInt(profile.shadows)}" """)
            appendLine("""    crs:Whites2012="${formatSignedInt(profile.whites)}" """)
            appendLine("""    crs:Blacks2012="${formatSignedInt(profile.blacks)}" """)
            appendLine("""    crs:Texture="${formatSignedInt(profile.texture)}" """)
            appendLine("""    crs:Clarity2012="${formatSignedInt(profile.clarity)}" """)
            appendLine("""    crs:Dehaze="${formatSignedInt(profile.dehaze)}" """)
            appendLine("""    crs:Vibrance="${formatSignedInt(profile.vibrance)}" """)
            appendLine("""    crs:Saturation="${formatSignedInt(profile.saturation)}" """)
            appendLine("""    crs:SplitToningShadowHue="${profile.shadowsHue}" """)
            appendLine("""    crs:SplitToningShadowSaturation="${profile.shadowsSaturation}" """)
            appendLine("""    crs:SplitToningHighlightHue="${profile.highlightsHue}" """)
            appendLine("""    crs:SplitToningHighlightSaturation="${profile.highlightsSaturation}" """)
            appendLine("""    crs:SplitToningBalance="0" """)
            appendLine("""    crs:ColorGradeShadowHue="${profile.shadowsHue}" """)
            appendLine("""    crs:ColorGradeShadowSat="${profile.shadowsSaturation}" """)
            appendLine("""    crs:ColorGradeShadowLum="0" """)
            appendLine("""    crs:ColorGradeMidtoneHue="${profile.midtonesHue}" """)
            appendLine("""    crs:ColorGradeMidtoneSat="${profile.midtonesSaturation}" """)
            appendLine("""    crs:ColorGradeMidtoneLum="0" """)
            appendLine("""    crs:ColorGradeHighlightHue="${profile.highlightsHue}" """)
            appendLine("""    crs:ColorGradeHighlightSat="${profile.highlightsSaturation}" """)
            appendLine("""    crs:ColorGradeHighlightLum="0" """)
            appendLine("""    crs:ColorGradeGlobalHue="0" """)
            appendLine("""    crs:ColorGradeGlobalSat="0" """)
            appendLine("""    crs:ColorGradeGlobalLum="0" """)
            appendLine("""    crs:ColorGradeBlending="50" """)
            appendLine("""    crs:PostCropVignetteAmount="${formatSignedInt(profile.vignette)}" """)
            appendLine("""    crs:PostCropVignetteMidpoint="50" """)
            appendLine("""    crs:PostCropVignetteFeather="50" """)
            appendLine("""    crs:PostCropVignetteRoundness="0" """)
            appendLine("""    crs:PostCropVignetteStyle="1" """)
            appendLine("""    crs:GrainAmount="${profile.grain}" """)
            appendLine("""    crs:GrainSize="25" """)
            appendLine("""    crs:GrainFrequency="50" """)
            appendLine("""    crs:HasSettings="True">""")
            appendLine("""   <crs:Name>""")
            appendLine("""    <rdf:Alt>""")
            appendLine("""     <rdf:li xml:lang="x-default">$escapedName</rdf:li>""")
            appendLine("""    </rdf:Alt>""")
            appendLine("""   </crs:Name>""")
            appendLine("""   <crs:ShortName>""")
            appendLine("""    <rdf:Alt>""")
            appendLine("""     <rdf:li xml:lang="x-default">$escapedName</rdf:li>""")
            appendLine("""    </rdf:Alt>""")
            appendLine("""   </crs:ShortName>""")
            appendLine("""   <crs:SortName>""")
            appendLine("""    <rdf:Alt>""")
            appendLine("""     <rdf:li xml:lang="x-default">$escapedName</rdf:li>""")
            appendLine("""    </rdf:Alt>""")
            appendLine("""   </crs:SortName>""")
            appendLine("""   <crs:Group>""")
            appendLine("""    <rdf:Alt>""")
            appendLine("""     <rdf:li xml:lang="x-default">GradeScan Studio</rdf:li>""")
            appendLine("""    </rdf:Alt>""")
            appendLine("""   </crs:Group>""")
            appendLine("""   <crs:Description>""")
            appendLine("""    <rdf:Alt>""")
            appendLine("""     <rdf:li xml:lang="x-default">$escapedNotes</rdf:li>""")
            appendLine("""    </rdf:Alt>""")
            appendLine("""   </crs:Description>""")
            appendLine("""  </rdf:Description>""")
            appendLine(""" </rdf:RDF>""")
            appendLine("""</x:xmpmeta>""")
        }
    }

    private fun formatSignedInt(value: Int): String = when {
        value > 0 -> "+$value"
        else -> value.toString()
    }

    private fun formatSignedFloat(value: Float): String {
        val formatted = String.format(Locale.US, "%.2f", value)
        return if (value > 0f && !formatted.startsWith("+")) "+$formatted" else formatted
    }

    private fun escapeXml(input: String): String = input
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("\"", "&quot;")
        .replace("'", "&apos;")
}
